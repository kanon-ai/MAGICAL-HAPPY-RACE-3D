"""Precompute the exact face/UV stream used by the existing arch renderer."""
from pathlib import Path
import json
R=Path(__file__).resolve().parents[1]
model=json.loads((R/'outputs/gate-arch-study/rock-arch-model.json').read_text())
arrays={}
for back in (False,True):
    order=[i*4+3 for i in range(8)]+[i*4+int(back) for i in range(8)]
    faces=[];uv=[]
    for i in order:
        faces.extend([180+v for v in model['faces'][i]]+[0]*6+[128])
        u=(i//4%4)*32
        uv.extend([u,0,u+31,0,u+31,63,u,63])
    assert len(faces)==176 and len(uv)==128
    arrays['arch_faces_'+('back' if back else 'front')]=faces
    if back:assert uv==arrays['arch_uv']
    else:arrays['arch_uv']=uv
text='/* Generated by tools/generate_arch_streams.py. */\n'
for name,data in arrays.items():
    text+='static const uint8_t '+name+'['+str(len(data))+']={'+','.join(map(str,data))+'};\n'
(R/'src/rock_arch_streams.h').write_text(text)
print('480 bytes of exact precomputed face/UV streams')
