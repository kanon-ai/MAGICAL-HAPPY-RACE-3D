"""Compact world-space arch model for the forthcoming native structure renderer.

XY units use the existing road normalisation: road edges +/-80, 64 =3.625m.
Z uses simulation distance units (16 per metre). No game ROM is changed here.
"""
from pathlib import Path
import math,json
from collections import Counter
R=Path(__file__).resolve().parents[1];O=R/'outputs/gate-arch-study';O.mkdir(exist_ok=True)
vertices=[]
for z in (-24,24):
 for radius,height in ((128,136),(96,100)):
  for i in range(9):
   angle=math.pi-i*math.pi/8
   vertices.append([round(radius*math.cos(angle)),round(height*math.sin(angle)),z])
faces=[]
for i in range(8):
 # Front, back, outer roof and opening soffit; each is a proper quad.
 faces.extend([[i,i+1,i+10,i+9],[18+i+9,18+i+10,18+i+1,18+i],
               [i,18+i,18+i+1,i+1],[9+i,10+i,28+i,27+i]])
faces.extend([[0,9,27,18],[8,26,35,17]])
assert len(vertices)==36 and len(faces)==34
assert all(0<=i<36 for f in faces for i in f)
assert all(vertices[i][1]==0 for i in (0,8,9,17,18,26,27,35))
edges=Counter((a,b) for f in faces for a,b in zip(f,f[1:]+f[:1]))
assert all(count==1 and edges[b,a]==1 for (a,b),count in edges.items()),'Open edge or inconsistent winding'
# Inner opening must clear both normal lanes, including a 4.1m-high truck
# envelope of +/-20 units around lane centres +/-40. Interpolate polygon edge.
inner=vertices[9:18]
def clearance(x):
 for a,b in zip(inner,inner[1:]):
  if a[0]<=x<=b[0]:return a[1]+(b[1]-a[1])*(x-a[0])/(b[0]-a[0])
 raise AssertionError(x)
minimum=min(clearance(x) for x in range(-60,61))
assert minimum*3.625/64>=4.1
model=dict(vertices=vertices,faces=faces,units=dict(xy_metres=3.625/64,z_metres=1/16),placement=dict(piece=12,distance=8192),road_edges=[-80,80],truck_envelope=dict(x=[-60,60],height_m=4.1),minimum_truck_clearance_m=minimum*3.625/64,closed_mesh_consistent_winding=True,native_integrated=False)
(O/'rock-arch-model.json').write_text(json.dumps(model,indent=2))
header='/* Generated by tools/generate_drive_structures.py; not hooked into gameplay yet. */\n'
header+='static const signed short rock_arch_vertices[36][3]={\n'+',\n'.join('{'+','.join(map(str,v))+'}' for v in vertices)+'\n};\n'
header+='static const unsigned char rock_arch_faces[34][4]={\n'+',\n'.join('{'+','.join(map(str,v))+'}' for v in faces)+'\n};\n'
(R/'src/rock_arch_model.h').write_text(header)
obj=''.join('v '+' '.join(map(str,v))+'\n' for v in vertices)+''.join('f '+' '.join(str(x+1) for x in f)+'\n' for f in faces)
(O/'rock-arch.obj').write_text(obj)
print(json.dumps(dict(vertices=36,quads=34,model_bytes=36*6+34*4,minimum_truck_clearance_m=model['minimum_truck_clearance_m'],native_integrated=False)))
